// Workspace spaces with their agents under them, in one list (the Spaces and
// Agents lists merged; made from the spaces mod, with the agents mod's rows).
//
// Spaces: stable colored avatars, worktrees under their checkout, grouped by
// machine when more than one is known. After a space's name, the repo its first
// terminal is in now, only where unusual: branch, ahead/behind. Click to switch,
// right-click for its menu, drag to reorder.
//
// Agents: under their space, in the order agents() gives them, each with its
// program's icon, a name (a tab someone named, else the agent's own title), how
// long since its state changed, and its status; its sub-agents under it as a
// tree. Click to go to its pane. The chevron at the end of a space's row folds
// its agents. No priority view and no pins here: the agents mod has those.
//
// Folding: spaces fold by themselves unless that is switched off (the button
// in the sidebar's header, sidebar-header; kept as shared "spaces.autofold"). Then
// only the space you're in is unfolded, plus any you unfolded by its chevron
// (they stay until folded again), and a folded space still shows the agents
// that need you. A folded space, and a folded machine, sums its agents up as
// one mark per state.

